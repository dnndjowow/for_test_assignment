def build_messages(product: ProductInput):
    return [
        {'role': 'system', 'content': SYSTEM_PROMPT},
        {
            'role': 'user',
            'content': json.dumps({'product': product.model_dump()}, ensure_ascii=False),
        },
    ]


def build_response_format():
    return {
        'type': 'json_schema',
        'json_schema': {
            'name': 'product_card',
            'strict': True,
            'schema': CardDraft.model_json_schema(),
        },
    }


def add_repair_message(messages: list, content: str, errors: list[str]):
    return [
        *messages,
        {'role': 'assistant', 'content': content},
        {
            'role': 'user',
            'content': (
                'Исправь ответ по исходным данным и верни полный объект JSON. '
                'Не добавляй факты для достижения нужной длины. Ошибки проверки:\n'
                + '\n'.join('- ' + error for error in errors)
            ),
        },
    ]
